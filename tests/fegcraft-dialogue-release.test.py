import copy
from contextlib import redirect_stdout
import hashlib
import importlib.util
import io
import json
import os
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('dialogue_release', ROOT / 'scripts/deploy/release-fegcraft-dialogue.py')
m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)

SITE = b'''server {
 listen 80;
 server_name vector.kibouakari.com;
 return 301 https://$host$request_uri;
}
server {
 listen [::]:443 ssl;
 server_name other.invalid vector.kibouakari.com;
 # ignored { server_name fake.invalid; }
 location / { proxy_set_header X-Test "quoted } ; { #"; proxy_pass http://app; }
}
'''


class Release(unittest.TestCase):
    def setUp(self):
        # Production requires root. Exercise transactions in CI without requiring root ownership.
        ownership = patch.object(m.os, 'chown', return_value=None)
        ownership.start(); self.addCleanup(ownership.stop)

    def test_exact_https_server_and_closed_public_files(self):
        result = m.patch_nginx(SITE).decode()
        self.assertEqual(result.count('location = /vector-fegcraft-assets/'), 2)
        self.assertLess(result.index('listen [::]:443 ssl;'), result.index('location ='))
        self.assertIn('proxy_pass http://app;', result)
        self.assertNotIn('/root/', result)
        self.assertEqual(m.patch_nginx(SITE.replace(b'other.invalid ', b'')).count(b'location ='), 2)
        for raw in (SITE.replace(b'vector.kibouakari.com', b'lookalike.invalid'),
                    SITE + SITE, SITE[:-2], SITE.replace(b'443 ssl', b'443')):
            with self.subTest(raw=raw), self.assertRaises(RuntimeError): m.patch_nginx(raw)
        with self.assertRaises(RuntimeError): m.patch_nginx(m.patch_nginx(SITE))

    def test_compose_layout_and_canonical_scope(self):
        for env in ('    environment:\n      VERSION: "26.2"\n', '    environment:\n      - VERSION=26.2\n', ''):
            raw = ('services:\n  mc:\n    image: game:existing\n' + env + '    volumes:\n      - ./data:/data\n  other:\n    image: other:existing\n').encode()
            result = m.patch_compose(raw, 'mc', 'sha256:synthetic').decode()
            self.assertIn('    image: "sha256:synthetic"', result)
            self.assertIn('RESOURCE_PACK_ENFORCE', result)
            self.assertTrue(result.endswith('  other:\n    image: other:existing\n'))
        for env in ('    environment: {VERSION: "26.2"}\n', '    environment:\n      <<: *shared\n',
                    '    environment:\n      RESOURCE_PACK: ""\n', '    environment:\n      VERSION: |\n        26.2\n'):
            with self.assertRaises(RuntimeError): m.patch_compose(('services:\n  mc:\n    image: game\n' + env).encode(), 'mc', 'pinned')
        before = {'services': {'mc': {'image': 'game', 'environment': {'VERSION': '26.2'}, 'networks': {'mc-net': None}}}}
        candidate = copy.deepcopy(before)
        candidate['services']['mc']['environment'].update(m.PACK_ENV); candidate['services']['mc']['image'] = 'pinned'
        m.validate_candidate(before, candidate, 'mc', 'pinned')
        candidate['services']['mc']['privileged'] = True
        with self.assertRaises(RuntimeError): m.validate_candidate(before, candidate, 'mc', 'pinned')

    def test_owned_properties_restore_keeps_other_settings(self):
        before = {'resource-pack': '', 'resource-pack-sha1': None, 'require-resource-pack': 'false'}
        raw = ('# regenerated by game\nmax-players=20\nresource-pack=' + m.PACK_PROPERTIES['resource-pack'].replace(':', '\\:') + '\nresource-pack-sha1=' + m.PACK_SHA1 + '\nrequire-resource-pack=true\n').encode()
        result = m.restore_properties(raw, before)
        self.assertIn(b'max-players=20\n', result)
        self.assertEqual(m.properties(result).get('resource-pack'), '')
        self.assertNotIn('resource-pack-sha1', m.properties(result))
        with self.assertRaises(RuntimeError): m.restore_properties(raw.replace(m.PACK_SHA1.encode(), b'changed'), before)

    def test_transaction_guards_and_partial_restore(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp); a = root / 'a'; b = root / 'b'; a.write_bytes(b'old')
            plan = {'files': []}
            m.record(root, a, b'new', plan); m.record(root, b, b'created', plan)
            m.write_records(root, plan); self.assertEqual(a.read_bytes(), b'new')
            b.write_bytes(b'unknown later edit')
            with self.assertRaises(RuntimeError): m.write_records(root, plan, reverse=True)
            self.assertEqual(a.read_bytes(), b'new')
            b.write_bytes(b'created'); m.write_records(root, plan, reverse=True)
            self.assertEqual(a.read_bytes(), b'old'); self.assertFalse(b.exists())
            (root / 'before-0').write_bytes(b'corrupt')
            with self.assertRaises(RuntimeError): m.write_records(root, plan, reverse=True)

    def test_release_and_failure_restoration_orchestration(self):
        for case in ('success', 'nginx-fail', 'probe-fail', 'unqualified', 'changed-code', 'recreate-fail', 'https-fail', 'floating-version'):
            with self.subTest(case=case), tempfile.TemporaryDirectory() as temp:
                root = Path(temp); data = root / 'game/data'; install = root / 'releases/installed'
                report = root / 'releases/report'; capture = root / 'releases/capture'; public = root / 'www/vector'
                for p in (data / 'DiscordIntegration-Data/vector', data / 'DiscordIntegration-Data/addons', data / 'config',
                          install / 'code', report / 'public-assets', capture, public.parent): p.mkdir(parents=True, exist_ok=True)
                app = root / 'app-compose'; app.write_text('unchanged app')
                game_compose = data.parent / 'docker-compose.yml'; game_compose.write_text('services:\n  mc:\n    image: old-game\n    environment:\n      VERSION: "26.2"\n')
                site = root / 'site'; site.write_bytes(SITE)
                marker = data / 'DiscordIntegration-Data/vector/introduction-v1.attempted'; marker.write_text('already delivered')
                token = data / 'DiscordIntegration-Data/vector/token'; token.write_text('ab' * 32)
                bridge = data / 'DiscordIntegration-Data/vector/bridge.properties'
                bridge.write_text('enabled=true\nintroductionEnabled=false\ntokenFile=/data/DiscordIntegration-Data/vector/token\navatarUrl=\n')
                addon = data / 'DiscordIntegration-Data/addons/vector-minecraft-0.1.0.jar'; addon.write_bytes(b'old addon')
                (data / 'config/Discord-Integration.toml').write_text('[webhook]\nenable=true\n')
                props = data / 'server.properties'; props.write_text('max-players=20\nresource-pack=\nrequire-resource-pack=false\n')
                (install / 'compose.json').write_text('private service profile')
                manifest = {'minecraft_image': 'sha256:pinned-game', 'files': {str(p): m.digest(p) for p in (bridge, addon, token)}}
                (install / 'manifest.json').write_text(json.dumps(manifest))
                (install / 'code/health.py').write_bytes(b'# synthetic probe\n')
                (install / 'code/read-probe.py').write_bytes(b'# synthetic probe\n')
                for name in m.SOURCE_FILES: (install / 'code' / name).write_bytes(b'# old source\n')
                if case == 'changed-code': (install / 'code/runtime.py').write_text('# later unknown edit\n')
                new_addon = b'captured addon'; (capture / 'vector-minecraft-0.1.0.jar').write_bytes(new_addon)
                assets = {name: m.sha(('public synthetic ' + name).encode()) for name in m.ASSETS}
                for name in assets: (report / 'public-assets' / name).write_bytes(('public synthetic ' + name).encode())
                (report / 'result.json').write_text(json.dumps({'revision': m.QUALIFIED, 'passed': case != 'unqualified',
                    'installation': str(install), 'capture': str(capture), 'dialogue_and_discord_capture_passed': True,
                    'statistics_dialogue_tests_passed': True}))
                (capture / 'result.json').write_text(json.dumps({'revision': m.QUALIFIED, 'passed': True,
                    'cleanup_verified': True, 'addon_sha256': m.sha(new_addon)}))
                game = {'Id': 'original-game', 'Image': 'sha256:pinned-game', 'Mounts': [{'Source': str(data), 'Destination': '/data', 'RW': True}],
                    'State': {'Running': True, 'StartedAt': 'synthetic-start', 'Health': {'Status': 'healthy'}},
                    'Config': {'Env': ['VERSION=26.2'], 'Labels': {'com.docker.compose.project': 'game',
                    'com.docker.compose.service': 'mc', 'com.docker.compose.project.config_files': str(game_compose),
                    'com.docker.compose.project.working_dir': str(data.parent)}}}
                calls = []; failed = [False]
                before_compose = {'services': {'mc': {'image': 'old-game', 'environment': {'VERSION': 'latest' if case == 'floating-version' else '26.2'}}}}
                candidate_compose = copy.deepcopy(before_compose)
                candidate_compose['services']['mc']['image'] = game['Image']; candidate_compose['services']['mc']['environment'].update(m.PACK_ENV)
                def command(*args, **kwargs):
                    calls.append(args)
                    if args[:3] == ('docker', 'image', 'inspect'): return b'[{"Id":"sha256:pinned-game"}]'
                    if args[:3] == ('docker', 'ps', '-aq'): return b'' if case == 'recreate-fail' and failed[0] else b'owned-game-id'
                    if args[:3] == ('git', '-C', str(root / 'repo')):
                        source = args[-1]
                        if source.endswith('install-fegcraft-assistant.py'): return b'HEALTH = \"# synthetic probe\\n\"\nREAD_PROBE = \"# synthetic probe\\n\"\n'
                        if source.endswith('announce-fegcraft-assistant.py'):
                            return ('from pathlib import Path\nimport json\ndef installation(service):\n return Path(' + repr(str(install)) + '), json.loads(Path(' + repr(str(install / 'manifest.json')) + ').read_text())\n').encode()
                        return b'# old source\n' if source.startswith(m.OLD) else b'# qualified source\n'
                    if args == ('nginx', '-t') and case == 'nginx-fail' and not failed[0]:
                        failed[0] = True; raise RuntimeError('SYNTHETIC_NGINX_FAILURE')
                    if '/code/read-probe.py' in args:
                        if case == 'probe-fail': raise RuntimeError('SYNTHETIC_PROBE_FAILURE')
                        return b'{"complete_statistics":true,"player_files":2}'
                    if args[:2] == ('docker', 'compose') and 'up' in args:
                        if case == 'recreate-fail' and not failed[0]:
                            failed[0] = True; raise RuntimeError('SYNTHETIC_RECREATE_FAILURE')
                        current = json.loads((install / 'manifest.json').read_text())
                        if current.get('dialogue_release'):
                            props.write_text('max-players=20\n' + ''.join(k + '=' + v + '\n' for k, v in m.PACK_PROPERTIES.items()))
                        game['Id'] = 'recreated-game'
                    if args[:2] == ('docker', 'logs'):
                        return b'Vector bridge registered; Discord input enabled in the linked chat channel.'
                    return b''
                def config(path, project): return candidate_compose if path.name == 'compose.candidate.yml' else before_compose
                protected_identity = {'app': ['unchanged', 'image', 'started']}
                with patch.multiple(m, ROOT=root, REPO=root / 'repo', DATA=data, INSTALL=install, REPORT=report,
                        CAPTURE=capture, PUBLIC=public, GAME_COMPOSE=game_compose, APP_COMPOSE=app, ASSETS=assets, ADDON_SHA=m.sha(new_addon), OLD_ADDON_SHA=m.sha(b'old addon')), \
                        patch.dict(os.environ, {'VECTOR_REQUIRE_LOGO_PACK': '1'}), patch.object(m, 'nginx_site', return_value=site), \
                        patch.object(m, 'inspect', side_effect=lambda name: game if name == m.GAME else {'Image': m.NATIVE_IMAGE, 'Mounts': [{'Source': str(install / 'code'), 'Destination': '/code', 'RW': False}], 'State': {'Running': True, 'Health': {'Status': 'healthy'}}}), \
                        patch.object(m, 'identities', return_value=protected_identity), patch.object(m, 'run', side_effect=command), \
                        patch.object(m, 'compose_config', side_effect=config), patch.object(m, 'verify_assets', side_effect=RuntimeError('SYNTHETIC_HTTPS_FAILURE') if case == 'https-fail' else None), \
                        patch.object(m, 'large_digest', side_effect=lambda path: m.INTEGRATION_SHA if path.suffix == '.jar' and path.name.startswith('dcintegration') else m.GAME_SHA), \
                        patch.object(m, 'wait_ready', side_effect=lambda name, game=False: copy.deepcopy(globals_game[0]) if name == m.GAME else {}), \
                        redirect_stdout(io.StringIO()):
                    globals_game = [game]
                    if case == 'success':
                        m.release()
                        releases = list((root / 'releases').glob('vector-fegcraft-dialogue-release-*'))
                        self.assertEqual(len(releases), 1)
                        plan = json.loads((releases[0] / 'plan.json').read_text())
                        self.assertEqual(plan['status'], 'deployed_pending_client_test')
                        self.assertIn('discordInputEnabled=true', bridge.read_text())
                        self.assertEqual(addon.read_bytes(), new_addon)
                        self.assertEqual(json.loads((install / 'manifest.json').read_text())['files'][str(addon)], m.sha(new_addon))
                        count = len(calls); m.release()
                        self.assertFalse(any(args[:2] == ('docker', 'stop') for args in calls[count:]))
                        m.rollback(releases[0])
                        self.assertEqual(json.loads((install / 'manifest.json').read_text()), manifest)
                        self.assertEqual(addon.read_bytes(), b'old addon')
                        self.assertFalse(public.exists())
                        count = len(calls); m.rollback(releases[0]); self.assertEqual(count, len(calls))
                    else:
                        with self.assertRaises(RuntimeError): m.release()
                        self.assertEqual(addon.read_bytes(), b'old addon')
                        self.assertEqual(site.read_bytes(), SITE)
                        if case in ('nginx-fail', 'unqualified', 'changed-code', 'https-fail', 'floating-version'):
                            self.assertFalse(any(args[:2] == ('docker', 'stop') for args in calls))
                    self.assertEqual(marker.read_text(), 'already delivered')
                    self.assertEqual(app.read_text(), 'unchanged app')
                    self.assertFalse(any('mc-send-to-console' in args or 'restart' in args for args in calls))
                    self.assertFalse(any(args[:2] == ('docker', 'stop') and args[-1] in m.OTHERS for args in calls))


if __name__ == '__main__': unittest.main()
